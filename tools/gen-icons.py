#!/usr/bin/env python3
"""Generate icons/catalog.scm from nvim-web-devicons.

Each entry keeps the Nerd Font glyph, a colour class and the upstream colour.
The class lets ideish take the actual colour from the Helix theme; the
upstream hex is the fallback when the theme has nothing for that class.

    python3 tools/gen-icons.py            # pinned commit
    python3 tools/gen-icons.py <commit>   # another commit
"""

import colorsys
import re
import sys
import urllib.request
from pathlib import Path

REPOSITORY = "https://github.com/nvim-tree/nvim-web-devicons"
COMMIT = "ec309a0eaff6ea967e58c275996155ab5c16938d"
SOURCES = {
    "filename": "lua/nvim-web-devicons/default/icons_by_filename.lua",
    "extension": "lua/nvim-web-devicons/default/icons_by_file_extension.lua",
}
OUTPUT = Path(__file__).resolve().parent.parent / "icons" / "catalog.scm"

ENTRY = re.compile(
    r'\[\s*"((?:[^"\\]|\\.)*)"\s*\]\s*=\s*\{\s*icon\s*=\s*"((?:[^"\\]|\\.)*)"\s*,\s*color\s*=\s*"(#[0-9A-Fa-f]{6})"'
)


def fetch(commit, path):
    url = f"https://raw.githubusercontent.com/nvim-tree/nvim-web-devicons/{commit}/{path}"
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def colour_class(hex_colour):
    r, g, b = (int(hex_colour[i : i + 2], 16) / 255 for i in (1, 3, 5))
    hue, lightness, saturation = colorsys.rgb_to_hls(r, g, b)
    if saturation < 0.18 or lightness < 0.12 or lightness > 0.93:
        return "grey"
    hue *= 360
    for limit, name in (
        (15, "red"),
        (40, "orange"),
        (70, "yellow"),
        (160, "green"),
        (195, "cyan"),
        (250, "blue"),
        (290, "purple"),
        (335, "magenta"),
        (360, "red"),
    ):
        if hue < limit:
            return name
    return "red"


def scheme_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def entries(text):
    for key, icon, colour in ENTRY.findall(text):
        yield key.lower(), icon, colour_class(colour), colour.lower()


def main():
    commit = sys.argv[1] if len(sys.argv) > 1 else COMMIT
    lines = [
        ";; Generated by tools/gen-icons.py. Do not edit.",
        f";; Upstream: {REPOSITORY} (MIT)",
        f";; Commit: {commit}",
        ";; Entry: (key glyph colour-class upstream-hex)",
        "",
        "(provide filename-entries extension-entries)",
        "",
    ]
    for name, path in SOURCES.items():
        lines.append(f"(define {name}-entries")
        lines.append("  '(")
        for key, icon, cls, colour in sorted(entries(fetch(commit, path))):
            lines.append(f"    ({scheme_string(key)} {scheme_string(icon)} {cls} {scheme_string(colour)})")
        lines.append("    ))")
        lines.append("")
    OUTPUT.write_text("\n".join(lines))
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
